export function getDuaaText(duaa: { id: string; text: string; textEn?: string }, isEn: boolean): string {
    if (isEn) {
        return duaa.textEn || ADIA_EN_MAP[duaa.id]?.text || duaa.text;
    }
    return duaa.text;
}

export function getDuaaSource(duaa: { id: string; source: string; sourceEn?: string }, isEn: boolean): string {
    if (isEn) {
        return duaa.sourceEn || ADIA_EN_MAP[duaa.id]?.source || duaa.source;
    }
    return duaa.source;
}

export function getRepetitionText(count: number, isEn: boolean): string {
    if (!isEn) {
        if (count === 1) return 'يُقرأ مرة واحدة';
        if (count === 2) return 'يُقرأ مرتين';
        return `يُقرأ ${count.toString().replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[+d])} مرات`;
    }
    if (count === 1) return 'Recited Once';
    if (count === 2) return 'Recited 2 times';
    return `Recited ${count} times`;
}
