export function getShortSeerahHeaderTitle(id: string | undefined, fallbackTitle: string, isEn: boolean): string {
    if (id) {
        const mapped = isEn ? SHORT_SEERAH_HEADER_TITLES_EN[id] : SHORT_SEERAH_HEADER_TITLES_AR[id];
        if (mapped) return mapped;
    }
    if (!fallbackTitle) return '';
    const clean = fallbackTitle
        .replace(/\([^)]*\)/g, '')
        .replace(/«[^»]*»/g, '')
        .replace(/^[\s✨📖⏱️📍🏷️👥🎯🤲🔍💡🌟]+/gu, '')
        .trim();
    const firstClause = clean.split(/[:–—\-،]/)[0].trim();
    const words = firstClause.split(/\s+/);
    return words.length <= 3 ? firstClause : words.slice(0, 3).join(' ');
}


