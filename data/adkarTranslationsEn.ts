function normalizeArabic(str: string): string {
    return str
        .replace(/[\u064B-\u065F\u0670\s\u06D6-\u06ED]/g, '')
        .replace(/[إأآا]/g, 'ا')
        .replace(/ة/g, 'ه')
        .replace(/ى/g, 'ي')
        .trim();
}

const NORMALIZED_MAP = new Map<string, AdhkarTranslation>();
for (const [key, val] of Object.entries(ADKAR_EN_MAP)) {
    NORMALIZED_MAP.set(normalizeArabic(key), val);
}

export function getAdhkarTranslation(arabicText: string): AdhkarTranslation | null {
    if (!arabicText) return null;
    if (ADKAR_EN_MAP[arabicText]) {
        return ADKAR_EN_MAP[arabicText];
    }
    const norm = normalizeArabic(arabicText);
    if (NORMALIZED_MAP.has(norm)) {
        return NORMALIZED_MAP.get(norm)!;
    }
    for (const [keyNorm, val] of NORMALIZED_MAP.entries()) {
        if (norm.includes(keyNorm) || keyNorm.includes(norm)) {
            return val;
        }
    }
    return null;
}
