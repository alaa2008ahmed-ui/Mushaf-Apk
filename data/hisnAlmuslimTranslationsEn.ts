const toArabicNumerals = (num: number) => String(num).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[+d]);

export function getHisnRepetitionText(count: number, isEn: boolean): string {
    if (isEn) {
        return count > 1 ? `Read ${count} times` : 'Read once';
    }
    return count > 1 
        ? (count === 2 ? 'يُقرأ مرتين' : `يُقرأ ${toArabicNumerals(count)} مرات`) 
        : 'يُقرأ مرة واحدة';
}

export function getHisnItemTranslation(
    catId: string, 
    index: number, 
    arabicItem?: { title?: string; text: string; source?: string }
): HisnItemTranslation {
    const key = `${catId}_${index}`;
    if (HISN_ITEMS_EN[key]) {
        return HISN_ITEMS_EN[key];
    }
    return {
        title: `Supplication ${index + 1}`,
        text: arabicItem?.text || '',
        source: arabicItem?.source || ''
    };
}

export function getHisnCategoryTranslation(catId: string, arabicTitle: string): HisnCategoryInfo {
    if (HISN_CATEGORIES_EN[catId]) {
        return HISN_CATEGORIES_EN[catId];
    }
    return {
        title: arabicTitle,
        subtitle: `Supplications of ${arabicTitle}`
    };
}
