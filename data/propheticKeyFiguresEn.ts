/**
 * Translates an Arabic key figure name into scholarly English.
 * Falls back to clean transliteration if unmapped.
 */
export function translateKeyFigure(name: string): string {
    if (!name) return '';
    const trimmed = name.trim();
    if (KEY_FIGURES_EN[trimmed]) {
        return KEY_FIGURES_EN[trimmed];
    }

    // Try without honorific suffix if present
    const cleaned = trimmed
        .replace(/ رضي الله عنهما?/g, '')
        .replace(/ رضي الله عنها/g, '')
        .replace(/ رضي الله عنهم/g, '')
        .replace(/ عليه السلام/g, '')
        .replace(/ ﷺ/g, '')
        .trim();

    if (KEY_FIGURES_EN[cleaned]) {
        const tr = KEY_FIGURES_EN[cleaned];
        if (trimmed.includes('رضي الله')) return `${tr} (RA)`;
        if (trimmed.includes('عليه السلام')) return `${tr} (AS)`;
        return tr;
    }

    // Heuristic replacements for general Arabic names/titles
    let result = trimmed
        .replace(/أبو /g, 'Abu ')
        .replace(/أم /g, 'Umm ')
        .replace(/بن /g, 'ibn ')
        .replace(/ابن /g, 'ibn ')
        .replace(/بنت /g, 'bint ')
        .replace(/رضي الله عنهما?/g, '(RA)')
        .replace(/رضي الله عنها/g, '(RA)')
        .replace(/رضي الله عنهم/g, '(RA)')
        .replace(/عليه السلام/g, '(AS)')
        .replace(/ﷺ/g, 'ﷺ');

    return result;
}

export function translateKeyFiguresList(figures?: string[]): string[] | undefined {
    if (!figures || figures.length === 0) return figures;
    return figures.map(f => translateKeyFigure(f));
}
